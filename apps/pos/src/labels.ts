export type LabelKey = keyof typeof EN;

/** Label lookup. Unknown keys fall through to the key name. */
export const L: Record<LabelKey, string> & Record<string, string> = new Proxy(EN as Record<string, string>, {
  get: (target, prop) => (typeof prop === "string" ? target[prop] ?? prop : undefined),
}) as Record<LabelKey, string> & Record<string, string>;


export const PAY_LABEL: Record<PaymentMethod, string> = new Proxy(
  {} as Record<PaymentMethod, string>,
  {
    get(_target, prop: PaymentMethod) {
      if (prop === "Cash") return L.cash;
      if (prop === "Card") return L.card;
      if (prop === "Bank") return L.bank;
      if (prop === "QR") return L.qr;
      if (prop === "Credit") return L.credit;
      return "";
    },
    has(_target, prop) {
      return (
        prop === "Cash" ||
        prop === "Card" ||
        prop === "Bank" ||
        prop === "QR" ||
        prop === "Credit"
      );
    },
    ownKeys() {
      return ["Cash", "Card", "QR", "Bank", "Credit"];
    },
    getOwnPropertyDescriptor(_target, prop) {
      return {
        enumerable: true,
        configurable: true,
        value: (PAY_LABEL as any)[prop],
      };
    },
  }
);

