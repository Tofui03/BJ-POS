/**
 * Reactive multi-lingual label proxy.
 * Reads currentLocale.value to reactively update in Vue templates.
 * When currentLocale.value === "bi", returns the original bilingual "EN / BM" format.
 */
export const L: Record<LabelKey, string> = new Proxy(RAW_BILINGUAL_L, {
  get(target, prop: string | symbol) {
    if (typeof prop !== "string") {
      return (target as any)[prop];
    }
    const loc: Locale = currentLocale.value;
    if (loc === "zh") {
      return MESSAGES.zh[prop as LabelKey] ?? MESSAGES.en[prop as LabelKey] ?? (target as any)[prop] ?? prop;
    }
    if (loc === "ms") {
      return MESSAGES.ms[prop as LabelKey] ?? MESSAGES.en[prop as LabelKey] ?? (target as any)[prop] ?? prop;
    }
    if (loc === "en") {
      return MESSAGES.en[prop as LabelKey] ?? (target as any)[prop] ?? prop;
    }
    // "bi" or fallback
    return (target as any)[prop] ?? (MESSAGES.en[prop as LabelKey] ? `${MESSAGES.en[prop as LabelKey]} / ${MESSAGES.ms[prop as LabelKey]}` : prop);
  },
  has(target, prop) {
    return prop in target || (typeof prop === "string" && prop in MESSAGES.en);
  },
  ownKeys(target) {
    return Array.from(new Set([...Reflect.ownKeys(target), ...Object.keys(MESSAGES.en)]));
  },
  getOwnPropertyDescriptor(target, prop) {
    return {
      enumerable: true,
      configurable: true,
      value: (L as any)[prop],
    };
  },
});

import type { PaymentMethod } from "@yf/core";

export const PAY_LABEL: Record<PaymentMethod, string> = new Proxy(
  {} as Record<PaymentMethod, string>,
  {
    get(_target, prop: PaymentMethod) {
      if (prop === "Cash") return L.cash;
      if (prop === "Card") return L.card;
      if (prop === "Bank") return L.bank;
      if (prop === "QR") return L.qr;
      if (prop === "Credit") return L.credit;
      return "";
    },
    has(_target, prop) {
      return (
        prop === "Cash" ||
        prop === "Card" ||
        prop === "Bank" ||
        prop === "QR" ||
        prop === "Credit"
      );
    },
    ownKeys() {
      return ["Cash", "Card", "QR", "Bank", "Credit"];
    },
    getOwnPropertyDescriptor(_target, prop) {
      return {
        enumerable: true,
        configurable: true,
        value: (PAY_LABEL as any)[prop],
      };
    },
  }
);

